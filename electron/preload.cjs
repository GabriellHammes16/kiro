const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('cadernoDesktop', {
  janelaPropria: process.platform === 'win32',
  coresDaJanela: cores => ipcRenderer.send('janela:cores', cores),
  definirVidro: (ligado, comDesfoque) => ipcRenderer.invoke('janela:vidro', ligado === true, comDesfoque === true),
  definirCorretor: ligado => ipcRenderer.send('corretor:definir', ligado === true),
  aoMenuDoCorretor: fn => ipcRenderer.on('corretor:menu', (_evento, dados) => fn(dados)),
  trocarPalavra: palavra => ipcRenderer.send('corretor:trocar', palavra),
  adicionarAoDicionario: palavra => ipcRenderer.send('corretor:adicionar', palavra),
  definirIdioma: codigo => ipcRenderer.send('idioma:definir', codigo),
  loadState: () => ipcRenderer.invoke('vault:load'),
  saveState: state => ipcRenderer.invoke('vault:save', state),
  conflictCopies: () => ipcRenderer.invoke('vault:conflicts'),
  capturaGlobal: ligado => ipcRenderer.invoke('captura-global', ligado === true),
  aoCapturaGlobal: fn => ipcRenderer.on('captura-global', () => fn()),
  openVault: () => ipcRenderer.invoke('vault:open'),
  openPluginsFolder: () => ipcRenderer.invoke('plugins:open'),
  vaultPath: () => ipcRenderer.invoke('vault:path'),
  chooseVault: () => ipcRenderer.invoke('vault:choose'),
  firstRun: () => ipcRenderer.invoke('vault:first-run'),
  setupVault: modo => ipcRenderer.invoke('vault:setup', modo),
  trash: () => ipcRenderer.invoke('vault:trash'),
  restore: pedido => ipcRenderer.invoke('vault:restore', pedido),
  history: pedido => ipcRenderer.invoke('vault:history', pedido),
  readHistory: pedido => ipcRenderer.invoke('vault:history-read', pedido),
  restoreHistory: pedido => ipcRenderer.invoke('vault:history-restore', pedido),
  saveAttachment: pedido => ipcRenderer.invoke('vault:attachment', pedido),
  openAttachment: caminho => ipcRenderer.invoke('vault:open-attachment', caminho),
  agentConfig: () => ipcRenderer.invoke('agent:config:get'),
  saveAgentConfig: parcial => ipcRenderer.invoke('agent:config:set', parcial),
  version: () => ipcRenderer.invoke('app:version'),
  printNote: () => ipcRenderer.invoke('nota:imprimir'),
  exportNotePdf: titulo => ipcRenderer.invoke('nota:pdf', titulo),
  plugins: () => ipcRenderer.invoke('plugins:list'),
  inspectPlugin: id => ipcRenderer.invoke('plugins:inspect', id),
  pluginChoices: () => ipcRenderer.invoke('plugins:choices:get'),
  savePluginChoices: escolhas => ipcRenderer.invoke('plugins:choices:set', escolhas),
  homeLayout: () => ipcRenderer.invoke('home:get'),
  saveHomeLayout: layout => ipcRenderer.invoke('home:set', layout),
  bookmarks: () => ipcRenderer.invoke('favoritos:get'),
  saveBookmarks: favoritos => ipcRenderer.invoke('favoritos:set', favoritos),
  dicionario: () => ipcRenderer.invoke('dicionario:get'),
  adicionarAoDicionarioDoCofre: palavra => ipcRenderer.invoke('dicionario:add', palavra),
  pluginData: id => ipcRenderer.invoke('plugins:data:get', id),
  savePluginData: (id, dados) => ipcRenderer.invoke('plugins:data:set', id, dados),
  pluginFetch: (id, pedido) => ipcRenderer.invoke('plugins:fetch', id, pedido),
  pluginSecrets: id => ipcRenderer.invoke('plugins:secrets:state', id),
  savePluginSecret: (id, nome, valor) => ipcRenderer.invoke('plugins:secrets:set', id, nome, valor),
  removePluginSecret: (id, nome) => ipcRenderer.invoke('plugins:secrets:remove', id, nome),
  backupStatus: () => ipcRenderer.invoke('backup:status'),
  saveBackupConfig: parcial => ipcRenderer.invoke('backup:config:set', parcial),
  runBackupNow: opcoes => ipcRenderer.invoke('backup:run', opcoes),
  chooseBackupFolder: () => ipcRenderer.invoke('backup:choose'),
  openBackupFolder: () => ipcRenderer.invoke('backup:open'),
  connectGoogleDrive: credenciais => ipcRenderer.invoke('backup:drive:connect', credenciais),
  disconnectGoogleDrive: () => ipcRenderer.invoke('backup:drive:disconnect')
});
